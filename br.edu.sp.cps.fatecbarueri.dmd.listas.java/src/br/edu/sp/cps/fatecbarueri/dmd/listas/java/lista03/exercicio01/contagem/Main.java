/*
 * Lista 3 - Exercício 1
 * Exibe os números de 1 até 10 usando for.
 */
public class Main {
    public static void main(String[] args) {
        for (int i = 1; i <= 10; i++) {
            System.out.println(i);
        }
    }
}
